#!/usr/bin/env python3
"""
Exports the numeric constants of the model's GUMBO library
(sysmlv2/SeedImaging.sysml: STEPS_PER_REV, MAX_MOVE_STEPS, TILT_LIMIT_STEPS, ...)
to the C / C++ implementation as si_model_constants.h, so the limits the code
enforces are exactly the ones the contracts are written against.

    python3 bin/gen_model_constants.py           # (re)write the headers
    python3 bin/gen_model_constants.py --check   # fail if a header is stale
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
MODEL = os.path.join(ROOT, "sysmlv2", "SeedImaging.sysml")
TARGETS = [
    os.path.join(ROOT, "hamr", "ros2", "microros_apps", "seed_imaging_microros_pkg", "include",
                 "seed_imaging_microros_pkg", "user_headers", "si_model_constants.h"),
    os.path.join(ROOT, "hamr", "ros2", "src", "seed_imaging_cpp_pkg", "include",
                 "seed_imaging_cpp_pkg", "user_headers", "si_model_constants.h"),
]

model = open(MODEL).read()
lib = model[model.index('language "GUMBO"'):]
lib = lib[:lib.index('}*/')]
consts = re.findall(r"def (\w+)\(\): Base_Types::Integer_32 :=\s*(-?\d+) \[s32\];", lib)
if not consts:
    sys.exit("no constants found in the GUMBO library of " + MODEL)

body = ["// GENERATED by bin/gen_model_constants.py from sysmlv2/SeedImaging.sysml -- do not edit.",
        "// The numeric constants of the model's GUMBO library, for the C / C++ implementation.",
        "#ifndef SI_MODEL_CONSTANTS_H",
        "#define SI_MODEL_CONSTANTS_H",
        ""]
for name, value in consts:
    body.append(f"#define SI_{name:<18} {value}")
body += ["", "#endif  // SI_MODEL_CONSTANTS_H", ""]
text = "\n".join(body)

check = "--check" in sys.argv
stale = []
for t in TARGETS:
    old = open(t).read() if os.path.exists(t) else None
    if old != text:
        stale.append(t)
        if not check:
            os.makedirs(os.path.dirname(t), exist_ok=True)
            open(t, "w").write(text)
if check:
    if stale:
        sys.exit("stale (run bin/gen_model_constants.py): " + ", ".join(os.path.relpath(s, ROOT) for s in stale))
    print("model constants in sync: " + ", ".join(f"{n}={v}" for n, v in consts))
else:
    print(("wrote " if stale else "unchanged: ") + ", ".join(f"{n}={v}" for n, v in consts))
